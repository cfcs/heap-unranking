    pub fn rev_colex_index(perm: &[u8]) -> usize {
        let n = perm.len();

        let mut used = vec![false; n];
        let mut rank = 0usize;

        for i in (0..n).rev() {
            let smaller_unused = (0..perm[i]).filter(|&v| !used[v as usize]).count();
            rank = rank * (i + 1) + smaller_unused;
            used[perm[i] as usize] = true;
        }
        (1..=perm.len()).product::<usize>() - 1 - rank
    }

